"""Procedural artefacts for the development simulator.

These are REAL 3DGS PLY / GLB / PNG files, written to the same conventions
ComfyUI-Idol produces, so the studio's validation, download, history and viewer
paths can be exercised without a GPU. They are NOT Idol inference output and
every file is labelled as simulated.
"""

from __future__ import annotations

import io
import json
import math
import struct
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

C0 = 0.28209479177387814


def torus_knot(n: int, seed: int = 42) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """A (2,3) torus knot tube sampled with n points: positions, radii, colours."""
    rng = np.random.default_rng(seed)
    t = np.linspace(0, 2 * math.pi, n, endpoint=False)
    p, q = 2, 3
    r = 0.55 + 0.25 * np.cos(q * t)
    x = r * np.cos(p * t)
    y = r * np.sin(p * t)
    z = 0.25 * np.sin(q * t) * 1.2

    # Slight tube jitter so it reads as a point cloud, not a line
    jitter = rng.normal(scale=0.018, size=(n, 3))
    x = x + jitter[:, 0]
    y = y + jitter[:, 1]
    z = z + jitter[:, 2]

    hue = (t / (2 * math.pi)) % 1.0
    cyan = np.stack([0.10 + 0.25 * hue, 0.75 + 0.2 * hue, 0.95 - 0.15 * hue], axis=1)
    violet = np.stack([0.55 + 0.3 * hue, 0.28 + 0.2 * hue, 0.95 - 0.1 * hue], axis=1)
    blend = (0.5 + 0.5 * np.sin(3 * t))[:, None]
    colors = cyan * (1 - blend) + violet * blend
    colors = np.clip(colors + rng.normal(scale=0.02, size=(n, 3)), 0, 1)

    scale = 0.012 + 0.01 * rng.random(n)
    return np.stack([x, y, z], axis=1).astype(np.float32), scale.astype(np.float32), colors.astype(np.float32)


def _rotation_quats(n: int, rng: np.random.Generator) -> np.ndarray:
    q = rng.normal(size=(n, 4))
    q /= np.linalg.norm(q, axis=1, keepdims=True)
    return q.astype(np.float32)


def gaussian_ply_bytes(n: int = 262_144, seed: int = 42, label: str = "simulated") -> bytes:
    rng = np.random.default_rng(seed)
    positions, scales, colors = torus_knot(n, seed)
    quats = _rotation_quats(n, rng)
    opacities = np.clip(0.92 + rng.normal(scale=0.03, size=n), 0, 0.999).astype(np.float32)

    # 3DGS storage convention: log scale, logit opacity, SH DC -> colour
    log_scales = np.log(scales)[:, None].repeat(3, axis=1).astype(np.float32)
    logit = np.log(opacities / (1 - opacities)).astype(np.float32)
    f_dc = ((colors - 0.5) / C0).astype(np.float32)

    normals = np.zeros_like(positions)
    attrs = (
        ["x", "y", "z", "nx", "ny", "nz"]
        + [f"f_dc_{i}" for i in range(3)]
        + ["opacity"]
        + [f"scale_{i}" for i in range(3)]
        + [f"rot_{i}" for i in range(4)]
    )
    elements = np.empty(n, dtype=[(a, "f4") for a in attrs])
    elements[:] = list(
        map(
            tuple,
            np.concatenate([positions, normals, f_dc, logit[:, None], log_scales, quats], axis=1),
        )
    )
    header = (
        "ply\nformat binary_little_endian 1.0\n"
        f"comment {label}: procedural torus knot generated by the development simulator\n"
        f"comment this is not Idol inference output\n"
        f"element vertex {n}\n"
    )
    header += "".join(f"property float {a}\n" for a in attrs) + "end_header\n"
    return header.encode("ascii") + elements.tobytes()


def _project(points: np.ndarray, size: int) -> np.ndarray:
    # Simple turntable-ish projection: rotate 30 deg about X and 35 about Y.
    ax, ay = math.radians(-24), math.radians(36)
    rx = np.array([[1, 0, 0], [0, math.cos(ax), -math.sin(ax)], [0, math.sin(ax), math.cos(ax)]])
    ry = np.array([[math.cos(ay), 0, math.sin(ay)], [0, 1, 0], [-math.sin(ay), 0, math.cos(ay)]])
    p = points @ rx.T @ ry.T
    z = p[:, 2] + 2.4
    scale = size * 0.42
    sx = size / 2 + (p[:, 0] / z) * scale
    sy = size / 2 - (p[:, 1] / z) * scale
    return np.stack([sx, sy], axis=1)


def preview_png_bytes(size: int = 1024, n: int = 40_000, background: str = "#0a0a0f") -> bytes:
    positions, scales, colors = torus_knot(n, seed=7)
    uv = _project(positions, size)
    order = np.argsort(-positions[:, 2])
    uv, colors, scales = uv[order], colors[order], scales[order]
    rgba = (colors * 255).astype(np.uint8)
    image = Image.new("RGB", (size, size), background)
    draw = ImageDraw.Draw(image, "RGBA")
    for (x, y), color, s in zip(uv, rgba, scales):
        r = max(1.0, float(s) * size * 0.55)
        draw.ellipse((x - r, y - r, x + r, y + r), fill=(int(color[0]), int(color[1]), int(color[2]), 235))
    stamp = "SIMULATED WORKER"
    draw.text((28, size - 44), stamp, fill=(255, 255, 255, 120))
    out = io.BytesIO()
    image.save(out, format="PNG", compress_level=6)
    return out.getvalue()


def mask_png_bytes(size: int = 1024) -> bytes:
    """White-on-black foreground mask, same convention as ComfyUI's MaskToImage."""
    image = Image.new("L", (size, size), 0)
    draw = ImageDraw.Draw(image)
    draw.ellipse((size * 0.18, size * 0.22, size * 0.82, size * 0.9), fill=255)
    out = io.BytesIO()
    image.convert("RGB").save(out, format="PNG", compress_level=6)
    return out.getvalue()


def model_input_png_bytes(size: int = 1024) -> bytes:
    positions, _, _ = torus_knot(30_000, seed=11)
    uv = _project(positions, size * 0.8)
    image = Image.new("RGB", (size, size), (0, 0, 0))
    draw = ImageDraw.Draw(image)
    for x, y in uv:
        draw.ellipse((x + size * 0.1 - 1.5, y + size * 0.1 - 1.5, x + size * 0.1 + 1.5, y + size * 0.1 + 1.5), fill=(120, 220, 255))
    draw.text((28, size - 44), "SIMULATED PREPROCESS", fill=(90, 90, 110))
    out = io.BytesIO()
    image.save(out, format="PNG", compress_level=6)
    return out.getvalue()


def _icosphere(subdivisions: int = 3) -> tuple[np.ndarray, np.ndarray]:
    t = (1 + 5**0.5) / 2
    verts = [
        [-1, t, 0], [1, t, 0], [-1, -t, 0], [1, -t, 0],
        [0, -1, t], [0, 1, t], [0, -1, -t], [0, 1, -t],
        [t, 0, -1], [t, 0, 1], [-t, 0, -1], [-t, 0, 1],
    ]
    faces = [
        (0, 11, 5), (0, 5, 1), (0, 1, 7), (0, 7, 10), (0, 10, 11),
        (1, 5, 9), (5, 11, 4), (11, 10, 2), (10, 7, 6), (7, 1, 8),
        (3, 9, 4), (3, 4, 2), (3, 2, 6), (3, 6, 8), (3, 8, 9),
        (4, 9, 5), (2, 4, 11), (6, 2, 10), (8, 6, 7), (9, 8, 1),
    ]
    v = [np.array(p, dtype=np.float64) / np.linalg.norm(p) for p in verts]
    f = [tuple(tri) for tri in faces]
    for _ in range(subdivisions):
        cache: dict[tuple[int, int], int] = {}
        new_faces = []

        def midpoint(a: int, b: int) -> int:
            key = (min(a, b), max(a, b))
            if key not in cache:
                m = (v[a] + v[b]) / 2.0
                v.append(m / np.linalg.norm(m))
                cache[key] = len(v) - 1
            return cache[key]

        for a, b, c in f:
            ab, bc, ca = midpoint(a, b), midpoint(b, c), midpoint(c, a)
            new_faces += [(a, ab, ca), (b, bc, ab), (c, ca, bc), (ab, bc, ca)]
        f = new_faces
    return np.array(v, dtype=np.float32), np.array(f, dtype=np.uint32)


def glb_bytes(subdivisions: int = 3) -> bytes:
    """A real, valid GLB (coloured icosphere) for exercising the GLB path."""
    verts, faces = _icosphere(subdivisions)
    # Squash into a knot-ish blob and colour it cyan->violet
    verts = verts * np.array([0.7, 0.55, 0.7], dtype=np.float32)
    colours = np.stack(
        [
            0.25 + 0.45 * (verts[:, 2] + 0.7),
            0.65 + 0.25 * (verts[:, 1] + 0.55),
            0.95 - 0.2 * (verts[:, 0] + 0.7),
        ],
        axis=1,
    ).astype(np.float32)
    colours = np.clip(colours, 0, 1)

    pos = verts.astype("<f4").tobytes()
    col = colours.astype("<f4").tobytes()
    idx = faces.astype("<u4").tobytes()
    pad = lambda b: b + b"\x00" * ((4 - len(b) % 4) % 4)  # noqa: E731
    pos, col, idx = pad(pos), pad(col), pad(idx)
    bin_blob = pos + col + idx

    doc = {
        "asset": {"version": "2.0", "generator": "idol-studio-development-simulator"},
        "scene": 0,
        "scenes": [{"nodes": [0]}],
        "nodes": [{"mesh": 0, "name": "SimulatedSplatMesh"}],
        "meshes": [
            {
                "name": "SimulatedSplatMesh",
                "primitives": [
                    {"attributes": {"POSITION": 0, "COLOR_0": 1}, "indices": 2, "mode": 4}
                ],
            }
        ],
        "buffers": [{"byteLength": len(bin_blob)}],
        "bufferViews": [
            {"buffer": 0, "byteOffset": 0, "byteLength": len(pos), "target": 34962},
            {"buffer": 0, "byteOffset": len(pos), "byteLength": len(col), "target": 34962},
            {"buffer": 0, "byteOffset": len(pos) + len(col), "byteLength": len(idx), "target": 34963},
        ],
        "accessors": [
            {
                "bufferView": 0,
                "componentType": 5126,
                "count": len(verts),
                "type": "VEC3",
                "min": verts.min(axis=0).tolist(),
                "max": verts.max(axis=0).tolist(),
            },
            {"bufferView": 1, "componentType": 5126, "count": len(verts), "type": "VEC3"},
            {"bufferView": 2, "componentType": 5125, "count": int(faces.size), "type": "SCALAR"},
        ],
        "extensionsUsed": ["KHR_materials_unlit"],
        "materials": [{"name": "unlit", "extensions": {"KHR_materials_unlit": {}}}],
    }
    json_blob = json.dumps(doc, separators=(",", ":")).encode()
    json_blob += b" " * ((4 - len(json_blob) % 4) % 4)
    total = 12 + 8 + len(json_blob) + 8 + len(bin_blob)
    out = bytearray()
    out += b"glTF" + struct.pack("<II", 2, total)
    out += struct.pack("<II", len(json_blob), 0x4E4F534A) + json_blob
    out += struct.pack("<II", len(bin_blob), 0x004E4942) + bin_blob
    return bytes(out)


def write_demo_artifacts(directory: Path, *, n_gaussians: int, with_glb: bool) -> dict[str, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    paths = {
        "ply": directory / "idol_00001_.ply",
        "preview": directory / "view_00001_.png",
        "model_input": directory / "model_input_00001_.png",
        "mask": directory / "mask_00001_.png",
    }
    paths["ply"].write_bytes(gaussian_ply_bytes(n_gaussians, label="SIMULATED"))
    paths["preview"].write_bytes(preview_png_bytes())
    paths["model_input"].write_bytes(model_input_png_bytes())
    paths["mask"].write_bytes(mask_png_bytes())
    if with_glb:
        paths["glb"] = directory / "mesh_00001_.glb"
        paths["glb"].write_bytes(glb_bytes())
    return paths
