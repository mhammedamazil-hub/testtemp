#!/usr/bin/env python3
"""Extract the input schema of the nodes this studio uses from a ComfyUI checkout.

The studio's workflow is built in code, not shipped as a template, so a silent
upstream rename (``num_gaussians`` -> ``num_samples``) would only show up at run
time, on the GPU, after a job was queued. This script turns the *installed*
ComfyUI source into a small JSON fixture that ``apps/api/tests/test_workflow_schema.py``
checks every generated workflow against.

Usage
-----
    git clone --depth 1 --branch v0.43.0 https://github.com/comfyanonymous/ComfyUI /tmp/comfy
    git clone --depth 1 https://github.com/PedroMarinhoDev/ComfyUI-Idol /tmp/idol
    python scripts/extract_comfy_schema.py \
        --comfy-dir /tmp/comfy \
        --idol-dir /tmp/idol \
        --out apps/api/tests/fixtures/comfy_schema.json

Sources are only read as text; nothing is imported, so no GPU or torch install
is needed.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# Node classes the workflows use, and the file that defines each one.
NODE_FILES: dict[str, list[str]] = {
    "comfy_extras/nodes_triposplat.py": ["TripoSplatConditioning", "VAEDecodeTripoSplat"],
    "comfy_extras/nodes_gaussian_splat.py": ["SplatToFile3D", "RenderSplat", "SplatToMesh"],
    "comfy_extras/nodes_save_3d.py": ["MeshToFile3D", "Save3DAdvanced", "SaveGaussianSplat"],
    "comfy_extras/nodes_bg_removal.py": ["LoadBackgroundRemovalModel", "RemoveBackground"],
    "comfy_extras/nodes_mask.py": ["MaskToImage"],
}
IDOL_FILES: dict[str, list[str]] = {
    "nodes.py": ["IdolPreprocessImage", "IdolInputCamera", "IdolPrecision"],
}

INPUT_RE = re.compile(r'IO\.[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)?\.Input\(\s*"([^"]+)"')
OUTPUT_RE = re.compile(r'IO\.[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)?\.Output\(')


def class_body(source: list[str], name: str) -> str | None:
    pattern = re.compile(rf"class {name}\(IO\.ComfyNode\)")
    for index, line in enumerate(source):
        if pattern.match(line):
            end = len(source)
            for cursor in range(index + 1, len(source)):
                line_cursor = source[cursor]
                if line_cursor and not line_cursor[0].isspace() and not line_cursor.startswith("#"):
                    end = cursor
                    break
            return "\n".join(source[index:end])
    return None


def extract(root: Path, files: dict[str, list[str]], into: dict[str, dict[str, object]]) -> list[str]:
    missing: list[str] = []
    for relative, classes in files.items():
        path = root / relative
        if not path.is_file():
            missing.append(str(path))
            continue
        source = path.read_text(encoding="utf-8").splitlines()
        for name in classes:
            body = class_body(source, name)
            if body is None:
                missing.append(f"{path}:{name}")
                continue
            inputs: list[str] = []
            for match in INPUT_RE.finditer(body):
                key = match.group(1)
                if key not in inputs:
                    inputs.append(key)
            into[name] = {"file": relative, "inputs": inputs, "outputs": len(OUTPUT_RE.findall(body))}
    return missing


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--comfy-dir", type=Path, required=True)
    parser.add_argument("--idol-dir", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--comfy-ref", default="v0.43.0")
    parser.add_argument("--idol-ref", default="ComfyUI-Idol")
    args = parser.parse_args()

    schema: dict[str, dict[str, object]] = {}
    missing = extract(args.comfy_dir, NODE_FILES, schema)
    missing += extract(args.idol_dir, IDOL_FILES, schema)
    if missing:
        print("Could not find:", ", ".join(missing), file=sys.stderr)
        return 1

    payload = {
        "_comment": (
            "Generated by scripts/extract_comfy_schema.py from ComfyUI "
            f"{args.comfy_ref} and {args.idol_ref}. Do not edit by hand; regenerate and commit."
        ),
        "comfyui": args.comfy_ref,
        "idol": args.idol_ref,
        "nodes": schema,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {args.out} ({len(schema)} node classes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
