/** Real PDF generation with jsPDF (validated by tests via the %PDF header). */

import type { Artifact } from '../types';

export async function buildPdf(options: { title: string; subtitle?: string; artifacts: Artifact[]; sources?: { title: string; text: string }[] }): Promise<Uint8Array> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4', compress: true });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 48;
  const maxWidth = pageWidth - margin * 2;
  let y = margin;

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - margin - 20) {
      doc.addPage();
      y = margin;
    }
  };

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  const titleLines = doc.splitTextToSize(options.title, maxWidth) as string[];
  doc.text(titleLines, margin, y);
  y += titleLines.length * 26;
  if (options.subtitle) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(90);
    const subLines = doc.splitTextToSize(options.subtitle, maxWidth) as string[];
    doc.text(subLines, margin, y);
    y += subLines.length * 13 + 8;
    doc.setTextColor(20);
  }
  y += 10;

  for (const artifact of options.artifacts) {
    ensureSpace(60);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(15);
    const heading = doc.splitTextToSize(artifact.title, maxWidth) as string[];
    doc.text(heading, margin, y);
    y += heading.length * 18 + 4;

    doc.setFont('helvetica', 'italic');
    doc.setFontSize(9);
    doc.setTextColor(110);
    doc.text(
      `${artifact.mode === 'ai' ? `AI-generated (${artifact.model ?? 'model'})` : 'Deterministic offline generation'} · ${new Date(artifact.createdAt).toISOString().slice(0, 10)}`,
      margin,
      y,
    );
    y += 16;
    doc.setTextColor(20);

    // Strip Markdown emphasis for a clean print body, keep structure.
    const plain = artifact.body
      .replace(/```[\s\S]*?```/g, '[code block omitted in PDF]')
      .replace(/^#{1,6}\s*/gm, '')
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/[*_`]/g, '')
      .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
      .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, '$1 ($2)');
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    for (const paragraph of plain.split('\n')) {
      if (!paragraph.trim()) {
        y += 6;
        continue;
      }
      const lineHeight = 13;
      const lines = doc.splitTextToSize(paragraph, maxWidth) as string[];
      for (const line of lines) {
        ensureSpace(lineHeight);
        doc.text(line, margin, y);
        y += lineHeight;
      }
    }
    if (artifact.citations.length) {
      y += 8;
      ensureSpace(30);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.text('Citations', margin, y);
      y += 13;
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      for (const citation of artifact.citations) {
        const text = `[${citation.marker}] ${citation.sourceTitle} — ${citation.locator}: ${citation.quote.slice(0, 160)}`;
        for (const line of doc.splitTextToSize(text, maxWidth) as string[]) {
          ensureSpace(11);
          doc.text(line, margin, y);
          y += 11;
        }
      }
    }
    y += 18;
  }

  if (options.sources?.length) {
    doc.addPage();
    y = margin;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(16);
    doc.text('Source excerpts', margin, y);
    y += 24;
    doc.setFontSize(9);
    for (const source of options.sources) {
      ensureSpace(40);
      doc.setFont('helvetica', 'bold');
      doc.text(doc.splitTextToSize(source.title, maxWidth) as string[], margin, y);
      y += 14;
      doc.setFont('helvetica', 'normal');
      for (const line of doc.splitTextToSize(source.text.slice(0, 2500), maxWidth) as string[]) {
        ensureSpace(12);
        doc.text(line, margin, y);
        y += 12;
      }
      y += 14;
    }
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i += 1) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(130);
    doc.text('Generated by SourceForge — verify claims against the original sources.', margin, pageHeight - 24);
    doc.text(`${i} / ${pages}`, pageWidth - margin - 30, pageHeight - 24);
  }

  return new Uint8Array(doc.output('arraybuffer') as ArrayBuffer);
}

export function isValidPdf(bytes: Uint8Array): boolean {
  if (bytes.length < 800) return false;
  const head = new TextDecoder('latin1').decode(bytes.subarray(0, 5));
  const tail = new TextDecoder('latin1').decode(bytes.subarray(-32));
  return head === '%PDF-' && tail.includes('%%EOF');
}
