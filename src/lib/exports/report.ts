/** Markdown and printable HTML study reports. */

import type { Artifact, Citation, Notebook, Source } from '../types';

export interface ReportInput {
  notebook: Notebook;
  sources: Source[];
  artifacts: Artifact[];
  exportedAt?: string;
}

export function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function citationFootnote(citation: Citation): string {
  return `[${citation.marker}] ${citation.sourceTitle} · ${citation.locator}`;
}

export function notebookMarkdown(input: ReportInput): string {
  const date = input.exportedAt ?? new Date().toISOString();
  const lines: string[] = [
    `# ${input.notebook.title}`,
    '',
    input.notebook.description ? `${input.notebook.description}\n` : '',
    `_Exported from SourceForge on ${date.slice(0, 10)} · ${input.sources.length} sources · ${input.artifacts.length} study items_`,
    '',
    '## Sources',
    '',
  ];
  for (const source of input.sources) {
    lines.push(`### ${source.title}`);
    lines.push(`- **Type:** ${source.kind}`);
    lines.push(`- **Status:** ${source.status} — ${source.statusDetail}`);
    if (source.origin.url) lines.push(`- **URL:** ${source.origin.url}`);
    if (source.origin.repo) lines.push(`- **Repository:** ${source.origin.repo}${source.origin.path ? ` / ${source.origin.path}` : ''}${source.origin.ref ? ` @ ${source.origin.ref}` : ''}`);
    lines.push('');
    lines.push(source.text.slice(0, 4000) + (source.text.length > 4000 ? '\n\n_(truncated in export — see the app for the full text)_' : ''));
    lines.push('');
  }
  for (const artifact of input.artifacts) {
    lines.push('---', '', `## ${artifact.title}`, '', `_${artifact.mode === 'ai' ? `AI (${artifact.model ?? 'model'})` : 'Deterministic offline generation'}_`, '', artifact.body, '');
    if (artifact.citations.length) {
      lines.push('**Citations**', '');
      for (const citation of artifact.citations) lines.push(`- ${citationFootnote(citation)}`);
      lines.push('');
    }
  }
  lines.push('---', '', '_Generated by SourceForge. Verify important claims against the original sources._');
  return lines.join('\n');
}

