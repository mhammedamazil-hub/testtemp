/** Minimal Markdown -> HTML for exported reports (headings, lists, tables, quotes, code, emphasis). */
export function markdownToHtml(markdown: string): string {
  const escape = escapeHtml;
  const lines = markdown.replace(/\r\n?/g, '\n').split('\n');
  const out: string[] = [];
  let inCode = false;
  let inList = false;
  let inTable = false;
  let inQuote = false;

  const closeBlocks = () => {
    if (inList) {
      out.push('</ul>');
      inList = false;
    }
    if (inTable) {
      out.push('</tbody></table>');
      inTable = false;
    }
    if (inQuote) {
      out.push('</blockquote>');
      inQuote = false;
    }
  };

  const inline = (text: string) =>
    escape(text)
      .replace(/`([^`]+)`/g, '<code>$1</code>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      .replace(/(^|[\s(])\*([^*\n]+)\*/g, '$1<em>$2</em>')
      .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '<a href="$2" rel="noopener noreferrer">$1</a>')
      .replace(/(\[\d+\])/g, '<sup class="cite">$1</sup>');

  for (const raw of lines) {
    const line = raw;
    if (/^```/.test(line.trim())) {
      if (inCode) {
        out.push('</code></pre>');
        inCode = false;
      } else {
        closeBlocks();
        out.push('<pre><code>');
        inCode = true;
      }
      continue;
    }
    if (inCode) {
      out.push(escape(line));
      continue;
    }
    if (!line.trim()) {
      closeBlocks();
      continue;
    }
    const heading = /^(#{1,4})\s+(.*)$/.exec(line);
    if (heading) {
      closeBlocks();
      const level = Math.min(heading[1].length + 1, 6);
      out.push(`<h${level}>${inline(heading[2])}</h${level}>`);
      continue;
    }
    if (/^\s*[-*]\s+/.test(line)) {
      if (!inList) {
        closeBlocks();
        out.push('<ul>');
        inList = true;
      }
      out.push(`<li>${inline(line.replace(/^\s*[-*]\s+/, ''))}</li>`);
      continue;
    }
    if (/^\s*>\s?/.test(line)) {
      if (!inQuote) {
        closeBlocks();
        out.push('<blockquote>');
        inQuote = true;
      }
      out.push(`<p>${inline(line.replace(/^\s*>\s?/, ''))}</p>`);
      continue;
    }
    if (/^\|.*\|$/.test(line.trim())) {
      if (/^\|[\s:|-]+\|$/.test(line.trim())) continue;
      const cells = line.trim().slice(1, -1).split('|').map((c) => c.trim());
      if (!inTable) {
        closeBlocks();
        out.push('<table><thead><tr>' + cells.map((c) => `<th>${inline(c)}</th>`).join('') + '</tr></thead><tbody>');
        inTable = true;
      } else {
        out.push('<tr>' + cells.map((c) => `<td>${inline(c)}</td>`).join('') + '</tr>');
      }
      continue;
    }
    if (/^---+$/.test(line.trim())) {
      closeBlocks();
      out.push('<hr />');
      continue;
    }
    closeBlocks();
    out.push(`<p>${inline(line)}</p>`);
  }
  closeBlocks();
  if (inCode) out.push('</code></pre>');
  return out.join('\n');
}

export function studyReportHtml(input: ReportInput): string {
  const date = input.exportedAt ?? new Date().toISOString();
  const artifactSections = input.artifacts
    .map(
      (artifact) => `
    <section class="artifact" id="artifact-${escapeHtml(artifact.id)}">
      <h2>${escapeHtml(artifact.title)}</h2>
      <p class="meta">${artifact.mode === 'ai' ? `AI-generated (${escapeHtml(artifact.model ?? 'model')})` : 'Deterministic offline generation'} · ${new Date(artifact.createdAt).toISOString().slice(0, 10)}</p>
      ${markdownToHtml(artifact.body)}
      ${
        artifact.citations.length
          ? `<div class="citations"><strong>Citations</strong><ul>${artifact.citations
              .map((c) => `<li>[${c.marker}] ${escapeHtml(c.sourceTitle)} · ${escapeHtml(c.locator)}<br /><span>${escapeHtml(c.quote.slice(0, 200))}</span></li>`)
              .join('')}</ul></div>`
          : ''
      }
    </section>`,
    )
    .join('\n');

  const sourceSections = input.sources
    .map(
      (source) => `
    <section class="source">
      <h3>${escapeHtml(source.title)} <span class="badge">${escapeHtml(source.kind)}</span></h3>
      <p class="meta">${escapeHtml(source.status)} — ${escapeHtml(source.statusDetail)}${
        source.origin.url ? ` · <a href="${escapeHtml(source.origin.url)}" rel="noopener noreferrer">original</a>` : ''
      }</p>
      ${source.warnings.length ? `<ul class="citations">${source.warnings.map((w) => `<li>${escapeHtml(w)}</li>`).join('')}</ul>` : ''}
      <pre>${escapeHtml(source.text.slice(0, 6000))}${source.text.length > 6000 ? '\n…' : ''}</pre>
    </section>`,
    )
    .join('\n');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${escapeHtml(input.notebook.title)} — SourceForge study report</title>
<style>${STYLES}</style>
</head>
<body>
<h1>${escapeHtml(input.notebook.title)}</h1>
<p class="meta">${escapeHtml(input.notebook.description || 'SourceForge research notebook')} · Exported ${escapeHtml(date.slice(0, 10))} · ${input.sources.length} sources · ${input.artifacts.length} study items</p>
${input.notebook.description ? `<p>${escapeHtml(input.notebook.description)}</p>` : ''}
<h2>Study material</h2>
${artifactSections || '<p>No study material was generated in this notebook yet.</p>'}
<h2>Sources</h2>
${sourceSections || '<p>No sources.</p>'}
<footer>Generated offline by SourceForge. Citations refer to the source locators shown above. Verify important claims against the originals.</footer>
</body>
</html>`;
}

export function artifactMarkdown(artifact: Artifact): string {
  const lines = [
    `# ${artifact.title}`,
    '',
    `_${artifact.mode === 'ai' ? `AI-generated (${artifact.model ?? 'model'})` : 'Deterministic offline generation'} · ${new Date(artifact.createdAt).toISOString()} · ${artifact.kind}_`,
    '',
    artifact.body,
  ];
  if (artifact.citations.length) {
    lines.push('', '## Citations', '');
    for (const c of artifact.citations) lines.push(`- ${citationFootnote(c)}`);
  }
  return lines.join('\n');
}
