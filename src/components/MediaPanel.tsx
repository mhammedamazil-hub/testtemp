import { useState, type ReactNode } from 'react';
import { actions, useAppState } from '../lib/store';
import { effectiveCapabilities, providerForTask } from '../lib/providers';
import { extractFrames, analyzeFrames, transcribeMediaFile, mediaTypeOf, type ExtractedFrame } from '../lib/ingest/media';
import { makeSource } from '../lib/ingest';
import { formatClock } from '../lib/text';
import { Spinner } from './ui';

export function MediaPanel(props: { notebookId: string; onAdded: () => void }): ReactNode {
  const state = useAppState();
  const [file, setFile] = useState<File | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [frames, setFrames] = useState<ExtractedFrame[]>([]);
  const [progress, setProgress] = useState(0);

  const transcriptionProvider = providerForTask(state.settings, 'transcription');
  const visionProvider = providerForTask(state.settings, 'vision');
  const mediaKind = file ? mediaTypeOf(file.name) : null;
  const browserFrames = typeof document !== 'undefined' && typeof URL.createObjectURL === 'function';

  const transcribe = async () => {
    if (!file || !transcriptionProvider) return;
    setBusy('Transcribing audio…');
    setError(null);
    try {
      const result = await transcribeMediaFile(file, transcriptionProvider);
      const segments = result.segments;
      const source = makeSource({
        notebookId: props.notebookId,
        title: `${file.name.replace(/\.[a-z0-9]+$/i, '')} (transcript)`,
        kind: 'media-transcript',
        text: result.text,
        segments,
        origin: { fileName: file.name, ...(result.language ? { author: undefined } : {}) },
        status: 'ready',
        statusDetail: `Transcribed with ${transcriptionProvider.label} (${segments.length} segments${result.language ? `, language ${result.language}` : ''}).`,
        warnings: ['Transcript generated by an external provider; check names and numbers against the audio.'],
      });
      await actions.addSources([source]);
      actions.toast('success', 'Transcript added to the notebook.');
      props.onAdded();
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      setError(message);
      actions.toast('error', `Transcription failed: ${message}`);
    } finally {
      setBusy(null);
    }
  };

  const sampleFrames = async () => {
    if (!file) return;
    setBusy('Sampling frames…');
    setError(null);
    setProgress(0);
    try {
      const extracted = await extractFrames(file, {
        intervalSeconds: 30,
        maxFrames: 6,
        onProgress: (done, total) => setProgress(Math.round((done / total) * 100)),
      });
      setFrames(extracted);
      actions.toast('info', `Sampled ${extracted.length} frame(s).`);
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      setError(message);
      actions.toast('error', message);
    } finally {
      setBusy(null);
    }
  };

  const describeFrames = async () => {
    if (!visionProvider || !frames.length || !file) return;
    setBusy('Analysing frames with the vision model…');
    setError(null);
    try {
      const analyses = await analyzeFrames(frames, visionProvider, { context: file.name });
      const body = analyses.map((a) => `[${formatClock(a.timeMs)}] ${a.description}`).join('\n');
      const source = makeSource({
        notebookId: props.notebookId,
        title: `${file.name.replace(/\.[a-z0-9]+$/i, '')} (frame analysis)`,
        kind: 'image-analysis',
        text: body,
        segments: analyses.map((a, i) => ({
          index: i,
          text: a.description,
          startMs: a.timeMs,
          endMs: a.timeMs + 1000,
          startLine: i + 1,
          endLine: i + 1,
        })),
        origin: { fileName: file.name },
        status: 'partial',
        statusDetail: `Descriptions of ${analyses.length} sampled frames from the vision model.`,
        warnings: [
          'Frame descriptions are model output, not ground truth, and only cover sampled timestamps.',
          'Verify anything important by watching the source video.',
        ],
      });
      await actions.addSources([source]);
      actions.toast('success', 'Frame analysis added as a source.');
      props.onAdded();
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      setError(message);
      actions.toast('error', `Frame analysis failed: ${message}`);
    } finally {
      setBusy(null);
    }
  };

  return (
    <div className="stack">
      <div className="notice notice--info">
        <strong>What runs where</strong>
        Audio/video decoding, frame sampling and playback happen in your browser. Transcription and frame descriptions need a configured
        provider (their audio/frames are sent to that provider). There is no bundled ffmpeg/yt-dlp and no video download — a static web app
        cannot invoke native binaries.
      </div>

      <div>
        <label htmlFor="media-file">Audio or video file</label>
        <input
          id="media-file"
          className="input"
          type="file"
          accept="audio/*,video/*,.mp3,.m4a,.wav,.ogg,.opus,.flac,.aac,.webm,.mp4,.mov,.mkv,.m4v"
          onChange={(event) => {
            setFile(event.target.files?.[0] ?? null);
            setFrames([]);
            setError(null);
          }}
        />
        <div className="hint">
          Max 24 MB for transcription. {mediaKind ? `Detected: ${mediaKind}.` : 'Supports common audio and video containers.'}
        </div>
      </div>

      <div className="cap-grid">
        <div className="cap-item">
          <span className={`badge ${transcriptionProvider ? 'badge--ready' : 'badge--partial'}`}>
            {transcriptionProvider ? 'Transcription ready' : 'No transcription provider'}
          </span>
          <span className="tiny faint">{transcriptionProvider ? transcriptionProvider.label : 'e.g. OpenAI whisper / Groq'}</span>
        </div>
        <div className="cap-item">
          <span className={`badge ${visionProvider ? 'badge--ready' : 'badge--partial'}`}>
            {visionProvider ? 'Vision ready' : 'No vision provider'}
          </span>
          <span className="tiny faint">{visionProvider ? visionProvider.label : 'needed to describe frames'}</span>
        </div>
        <div className="cap-item">
          <span className={`badge ${browserFrames ? 'badge--ready' : 'badge--partial'}`}>{browserFrames ? 'Frame sampling available' : 'Frame sampling unavailable'}</span>
          <span className="tiny faint">HTMLVideoElement + canvas</span>
        </div>
      </div>

      {error ? (
        <div className="notice notice--error" role="alert">
          <strong>Media processing problem</strong>
          {error}
        </div>
      ) : null}

      {busy ? (
        <div>
          <Spinner label={busy} />
          {progress > 0 && progress < 100 ? (
            <div className="progress">
              <div className="progress__bar" style={{ width: `${progress}%` }} />
            </div>
          ) : null}
        </div>
      ) : null}

      <div className="btn-row">
        <button
          type="button"
          className="btn btn--primary"
          disabled={!file || !transcriptionProvider || Boolean(busy)}
          onClick={() => void transcribe()}
        >
          Transcribe audio
        </button>
        <button
          type="button"
          className="btn"
          disabled={!file || mediaKind !== 'video' || !browserFrames || Boolean(busy)}
          onClick={() => void sampleFrames()}
        >
          Sample 6 frames
        </button>
        <button
          type="button"
          className="btn"
          disabled={!frames.length || !visionProvider || Boolean(busy)}
          onClick={() => void describeFrames()}
        >
          Describe frames
        </button>
      </div>

      {!transcriptionProvider ? (
        <p className="small faint">
          To transcribe, add a provider with the transcription capability in{' '}
          <button type="button" className="btn btn--ghost btn--sm" onClick={() => actions.setView('settings')}>
            Settings
          </button>
          . Without one you can still paste a transcript, or upload a .vtt/.srt caption file on the Files tab.
        </p>
      ) : null}

      {frames.length ? (
        <div className="stack">
          <div className="small muted">Sampled frames (not yet a source — describe them to extract text):</div>
          <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(140px, 1fr))', gap: '0.5rem' }}>
            {frames.map((frame) => (
              <figure key={frame.timeMs} style={{ margin: 0 }}>
                <img src={frame.dataUrl} alt={`Frame at ${formatClock(frame.timeMs)}`} style={{ width: '100%', borderRadius: 6 }} />
                <figcaption className="tiny faint">{formatClock(frame.timeMs)}</figcaption>
              </figure>
            ))}
          </div>
        </div>
      ) : null}
    </div>
  );
}

/** Small helper used by Settings to describe capability state consistently. */
export function CapabilityList(props: { caps: ReturnType<typeof effectiveCapabilities> }): ReactNode {
  const entries: [string, boolean][] = [
    ['Text', props.caps.text],
    ['Vision', props.caps.vision],
    ['Embeddings', props.caps.embeddings],
    ['Speech synthesis', props.caps.tts],
    ['Transcription', props.caps.transcription],
    ['Streaming', props.caps.streaming],
  ];
  return (
    <div className="cap-grid">
      {entries.map(([label, ok]) => (
        <div key={label} className="cap-item">
          <span className={`badge ${ok ? 'badge--ready' : ''}`}>{ok ? '✓' : '—'}</span>
          <span>{label}</span>
        </div>
      ))}
    </div>
  );
}
